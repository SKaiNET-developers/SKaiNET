"""PyTorch reference cases for convTranspose2d (#1372).

Prints the Kotlin fixture `ConvTranspose2dTorchReference.kt` used by `ConvTranspose2dOpsTest`:
`torch.nn.functional.conv_transpose2d` on seeded inputs over the parameter grid of the issue —
stride (1,1) / (2,2) / (2,1), padding (0,0) / (1,1), output padding (0,0) / (1,1), dilation
(1,1) / (2,2), groups 1 / 2, with and without bias. Input is `[1, 4, 3, 4]` and the kernel 3x2,
both non-square so that a swapped height / width shows.

    python3 scripts/reference/conv_transpose2d_reference.py > \
        skainet-backends/skainet-backend-cpu/src/commonTest/kotlin/sk/ainet/exec/ops/ConvTranspose2dTorchReference.kt

Every output shape is checked against
`(in - 1) * stride - 2 * padding + dilation * (k - 1) + outputPadding + 1`.
`--raises` prints the argument combinations PyTorch rejects instead of the fixture.
"""
import sys

import numpy as np
import torch
import torch.nn.functional as F

SEED = 1372
C_IN, C_OUT, IN_H, IN_W, K_H, K_W = 4, 4, 3, 4, 3, 2

# name, stride, padding, output_padding, dilation, groups, bias
CASES = [
    ("defaults", (1, 1), (0, 0), (0, 0), (1, 1), 1, False),
    ("stride2_padding1_outputPadding1_bias", (2, 2), (1, 1), (1, 1), (1, 1), 1, True),
    ("stride2x1_groups2_bias", (2, 1), (0, 0), (0, 0), (1, 1), 2, True),
    ("padding1_dilation2", (1, 1), (1, 1), (0, 0), (2, 2), 1, False),
    ("stride2_outputPadding1_dilation2_groups2_bias", (2, 2), (0, 0), (1, 1), (2, 2), 2, True),
    ("stride2x1_padding1x0_outputPadding1x0", (2, 1), (1, 0), (1, 0), (1, 1), 1, False),
    ("stride1_outputPadding1_dilation2", (1, 1), (0, 0), (1, 1), (2, 2), 1, False),
]


def arr(t):
    return "floatArrayOf(" + ", ".join(str(np.float32(x)) + "f" for x in t.reshape(-1).tolist()) + ")"


def ints(values):
    return "intArrayOf(" + ", ".join(str(v) for v in values) + ")"


def fixture():
    torch.manual_seed(SEED)
    out = [
        "package sk.ainet.exec.ops",
        "",
        "/**",
        f" * `torch.nn.functional.conv_transpose2d` outputs from PyTorch {torch.__version__.split('+')[0]} (float32,",
        f" * `torch.manual_seed({SEED})`), row-major. Generated by `scripts/reference/conv_transpose2d_reference.py`",
        " * (#1372); do not edit by hand.",
        " */",
        "internal object ConvTranspose2dTorchReference {",
        "    class Case(",
        "        val name: String,",
        "        val inputShape: IntArray, val input: FloatArray,",
        "        val weightShape: IntArray, val weight: FloatArray,",
        "        val bias: FloatArray?,",
        "        val stride: Pair<Int, Int>, val padding: Pair<Int, Int>,",
        "        val outputPadding: Pair<Int, Int>, val dilation: Pair<Int, Int>,",
        "        val groups: Int,",
        "        val outputShape: IntArray, val output: FloatArray,",
        "    )",
        "",
        "    val cases: List<Case> = listOf(",
    ]
    for name, stride, padding, output_padding, dilation, groups, with_bias in CASES:
        x = torch.randn(1, C_IN, IN_H, IN_W)
        w = torch.randn(C_IN, C_OUT // groups, K_H, K_W)
        b = torch.randn(C_OUT) if with_bias else None
        y = F.conv_transpose2d(x, w, b, stride, padding, output_padding, groups, dilation)
        expected = [
            (i - 1) * s - 2 * p + d * (k - 1) + op + 1
            for i, k, s, p, op, d in zip((IN_H, IN_W), (K_H, K_W), stride, padding, output_padding, dilation)
        ]
        assert list(y.shape) == [1, C_OUT, *expected], (name, y.shape, expected)
        pair = lambda p: f"{p[0]} to {p[1]}"
        out += [
            "        Case(",
            f'            name = "{name}",',
            f"            inputShape = {ints(x.shape)}, input = {arr(x)},",
            f"            weightShape = {ints(w.shape)}, weight = {arr(w)},",
            f"            bias = {arr(b) if b is not None else 'null'},",
            f"            stride = {pair(stride)}, padding = {pair(padding)},",
            f"            outputPadding = {pair(output_padding)}, dilation = {pair(dilation)},",
            f"            groups = {groups},",
            f"            outputShape = {ints(y.shape)}, output = {arr(y)},",
            "        ),",
        ]
    out += ["    )", "}"]
    print("\n".join(out))


def raises():
    x = torch.randn(1, C_IN, IN_H, IN_W)
    w = torch.randn(C_IN, C_OUT, K_H, K_W)
    probes = [
        ("output_padding == stride, dilation 1", dict(stride=(2, 2), output_padding=(2, 2))),
        ("output_padding 1, stride 1, dilation 1", dict(output_padding=(1, 1))),
        ("output_padding 1, stride 1, dilation 2", dict(output_padding=(1, 1), dilation=(2, 2))),
        ("groups 3 with 4 input channels", dict(groups=3)),
        ("padding larger than the output (padding 3)", dict(padding=(3, 3))),
        ("negative padding", dict(padding=(-1, -1))),
        ("stride 0", dict(stride=(0, 0))),
    ]
    for label, kwargs in probes:
        try:
            y = F.conv_transpose2d(x, w, **kwargs)
            print(f"accepted  {label}: output {list(y.shape)}")
        except Exception as e:  # noqa: BLE001 - report whatever PyTorch raises
            print(f"raises    {label}: {type(e).__name__}: {str(e).splitlines()[0]}")
    try:
        F.conv_transpose2d(x, torch.randn(3, C_OUT, K_H, K_W))
        print("accepted  weight with 3 input channels for a 4-channel input")
    except Exception as e:  # noqa: BLE001
        print(f"raises    weight with 3 input channels for a 4-channel input: {type(e).__name__}: {str(e).splitlines()[0]}")


if __name__ == "__main__":
    raises() if "--raises" in sys.argv else fixture()
