"""PyTorch reference values for GroupNormalization (#1380).

Prints the Kotlin fixture `GroupNormTorchReference.kt` used by `GroupNormalizationTest`:
`torch.nn.GroupNorm` on one seeded `[2, 6, 3, 3]` input with `num_groups` 1, 2, 3 and 6 and
non-trivial gamma / beta, plus one case with `affine=False`.

    python3 scripts/reference/groupnorm_reference.py > \
        skainet-backends/skainet-backend-cpu/src/commonTest/kotlin/sk/ainet/lang/nn/normalization/GroupNormTorchReference.kt

`torch.nn.GroupNorm` uses the biased variance (divide by the number of elements of the group):
https://pytorch.org/docs/stable/generated/torch.nn.GroupNorm.html ("The standard-deviation is
calculated via the biased estimator, equivalent to torch.var(input, unbiased=False)").
The script asserts that against a hand computation before printing.
"""
import numpy as np
import torch

SEED = 1380
N, C, H, W = 2, 6, 3, 3
EPS = 1e-5


def kt(name, t):
    body = ", ".join(str(np.float32(x)) + "f" for x in t.detach().reshape(-1).tolist())
    return f"    val {name} = floatArrayOf({body})"


def by_hand(x, groups, unbiased):
    g = x.reshape(N, groups, -1)
    return ((g - g.mean(-1, keepdim=True)) / torch.sqrt(g.var(-1, unbiased=unbiased, keepdim=True) + EPS)).reshape(x.shape)


torch.manual_seed(SEED)
x = torch.randn(N, C, H, W)
gamma = torch.randn(C)
beta = torch.randn(C)

lines = [
    "package sk.ainet.lang.nn.normalization",
    "",
    "/**",
    f" * `torch.nn.GroupNorm` outputs from PyTorch {torch.__version__.split('+')[0]} (float32, `torch.manual_seed({SEED})`, eps {EPS}),",
    " * row-major. Generated by `scripts/reference/groupnorm_reference.py` (#1380); do not edit by hand.",
    " */",
    "internal object GroupNormTorchReference {",
    f"    val shape = intArrayOf({N}, {C}, {H}, {W})",
    kt("input", x),
    kt("gamma", gamma),
    kt("beta", beta),
]
for groups in (1, 2, 3, 6):
    gn = torch.nn.GroupNorm(groups, C, eps=EPS, affine=True)
    with torch.no_grad():
        gn.weight.copy_(gamma)
        gn.bias.copy_(beta)
    lines.append(kt(f"affineGroups{groups}", gn(x)))
    plain = torch.nn.GroupNorm(groups, C, eps=EPS, affine=False)(x)
    assert torch.allclose(plain, by_hand(x, groups, unbiased=False), atol=1e-6), "biased variance expected"
    if groups < 6:  # a group of more than one element: the two estimators must differ
        assert not torch.allclose(plain, by_hand(x, groups, unbiased=True), atol=1e-4)
    if groups == 3:
        lines.append(kt("plainGroups3", plain))
lines.append("}")
print("\n".join(lines))
